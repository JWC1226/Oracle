/*
테이블 생성 : MEMBER
ID 컬럼 (숫자,기본키)
NAME 컬럼 (문자 50바이트 가변길이, NOT NULL)
EMAIL 컬럼 (문자 100바이트 가변길이,NOT NULL)
AGE 컬럼(숫자)

시퀀스 생성 : SEQ_MEMBER_ID
시작 번호 1 증가값 1 캐시 X

*/
CREATE TABLE MEMBER (
ID NUMBER PRIMARY KEY,
NAME VARCHAR2(50) NOT NULL,
EMAIL VARCHAR2(100) NOT NULL,
AGE NUMBER

);
CREATE SEQUENCE SEQ_MEMBER_ID
START WITH 1
INCREMENT BY 1
NOCACHE;


SELECT *
FROM MEMBER;