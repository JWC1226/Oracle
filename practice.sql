CREATE TABLE MEMBERS22 (
    MEMBER_ID NUMBER PRIMARY KEY,
    NAME VARCHAR2(50) NOT NULL,
    GENDER VARCHAR2(10) NOT NULL,
    AGE NUMBER NOT NULL,
    HEIGHT NUMBER(5, 2) NOT NULL, -- 미터 단위(m) 저장 (예: 1.75)
    WEIGHT NUMBER(5, 2) NOT NULL  -- kg 단위 저장 (예: 70.5)
);

-- 자동 증가 ID를 위한 시퀀스 생성
CREATE SEQUENCE SEQ_MEMBER_ID START WITH 1 INCREMENT BY 1;

